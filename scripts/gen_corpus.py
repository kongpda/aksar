"""Generate the shaping test corpus (testdata/corpus/km.txt) below its marker line.

    python3 scripts/gen_corpus.py

Lines above the marker are written by hand and kept. Everything below is rebuilt, the same
every run: the alphabet in combinations (every consonant with every subscript, coeng-RO,
vowels, shifters, signs), digits and punctuation, and real words from the bundled ICU list
(crates/aksar/data/khmer-words.txt, Unicode License v3). Then run scripts/gen_golden.py.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORPUS = ROOT / "testdata/corpus/km.txt"
WORDS = ROOT / "crates/aksar/data/khmer-words.txt"
MARKER = "# ---- generated by scripts/gen_corpus.py, do not edit below ----"

COENG = "្"
RO = "រ"
CONSONANTS = [chr(c) for c in range(0x1780, 0x17A3)]  # 33, ក..អ
INDEPENDENT = [chr(c) for c in range(0x17A3, 0x17B4)]  # ឣ..ឳ
VOWELS = [chr(c) for c in range(0x17B6, 0x17C6)]  # ា..ៅ
SPLIT = "ើឿៀោៅ"
SIGNS = "ំះៈ់៍៎៏័៑៝៌"
PUNCT = "។៕៖ៗ៘៙៚៛ៜ"
DIGITS = "០១២៣៤៥៦៧៨៩"
# Consonants that take each shifter (series change).
MUUSIKATOAN = "ងញមយរវ"
TRIISAP = "សហអប"
WORD_LINES = 800
WORDS_PER_LINE = 3


def alphabet():
    out = ["# Every consonant with every subscript"]
    for c in CONSONANTS:
        out.append(" ".join(c + COENG + s for s in CONSONANTS))
    out.append("# Coeng-RO: alone, with a vowel, after another subscript")
    for c in CONSONANTS:
        out.append(" ".join([c + COENG + RO, c + COENG + RO + "ា", c + COENG + RO + "ើ"]
                            + [c + COENG + s + COENG + RO + "ី" for s in "កតបមស"]))
    out.append("# Every dependent vowel on every consonant")
    for c in CONSONANTS:
        out.append(" ".join(c + v for v in VOWELS))
    out.append("# Split vowels with subscripts and coeng-RO")
    for c in CONSONANTS:
        out.append(" ".join(c + COENG + s + v for s, v in zip("កខងតនមលវសហ", SPLIT * 2))
                   + " " + " ".join(c + COENG + RO + v for v in SPLIT))
    out.append("# Signs on consonants, alone and after a vowel")
    for c in CONSONANTS:
        out.append(" ".join(c + s for s in SIGNS) + " " + " ".join(c + v + s for v, s in zip("ាុេោិ", "ំះំះ់")))
    out.append("# Register shifters, with vowels and subscripts")
    for c in MUUSIKATOAN:
        out.append(" ".join(c + "៉" + v for v in VOWELS) + " " + c + COENG + "គ៉ា")
    for c in TRIISAP:
        out.append(" ".join(c + "៊" + v for v in VOWELS) + " " + c + COENG + "ត៊ី")
    out.append("# Independent vowels, alone and with signs")
    out.append(" ".join(INDEPENDENT))
    out.append(" ".join(v + s for v in INDEPENDENT for s in "ំះ"))
    out.append("# Digits and punctuation")
    for i in range(10):
        out.append("".join(DIGITS[(i + j) % 10] for j in range(i + 1)) + " " + PUNCT[i % len(PUNCT)])
    out.append(" ".join(PUNCT))
    out.append("៰៱៲៳៴៵៶៷៸៹ ᧠᧡᧢᧣᧤᧥᧦᧧᧨᧩᧪᧫᧬᧭᧮᧯᧰᧱᧲᧳᧴᧵᧶᧷᧸᧹᧺᧻᧼᧽᧾᧿")
    return out


def words():
    ws = [w for w in WORDS.read_text("utf-8").splitlines() if w and not w.startswith("#")]
    n = WORD_LINES * WORDS_PER_LINE
    step = len(ws) / n
    picked = [ws[int(i * step)] for i in range(n)]
    out = ["# Words from the ICU list (evenly spaced), joined by space, ZWSP or nothing"]
    for i in range(WORD_LINES):
        joiner = [" ", "​", ""][i % 3]
        line = joiner.join(picked[i * WORDS_PER_LINE:(i + 1) * WORDS_PER_LINE])
        if i % 7 == 0:
            line += "។"
        out.append(line)
    return out


def main():
    text = CORPUS.read_text("utf-8")
    if MARKER not in text:
        # Without it the old generated block would be kept as hand-written text.
        sys.exit(f"marker line not found in {CORPUS}: {MARKER}")
    head = text.split(MARKER)[0].rstrip("\n")
    lines = alphabet() + words()
    CORPUS.write_text(head + "\n" + MARKER + "\n" + "\n".join(lines) + "\n", "utf-8")
    print(f"{sum(1 for l in lines if not l.startswith('#'))} generated lines")


if __name__ == "__main__":
    main()
